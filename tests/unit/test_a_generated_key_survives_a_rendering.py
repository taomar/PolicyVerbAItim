def test_a_key_that_occurs_twice_is_withheld_and_restored_twice():
    """Fourteen hundred records here repeat an opaque value; the unit this
    boundary was built for carries its key twice. One marker for both could not
    tell a rendering that returned it once from one that returned it twice."""

    text = f"Under {KEY} the balance accrues. Requests cite {KEY} on the form."
    recorded = _spans(text, KEY)
    assert len(recorded) == 2

    protector = _OpaqueText({"rule-0": recorded}, texts=[text])
    hidden = protector.hide("rule-0", text)

    assert KEY not in hidden
    markers = {token for token in hidden.split() if protector._prefix in token}
    assert len(markers) == 2, "both occurrences were given the same marker"
    assert protector.show("rule-0", hidden) == text


def test_the_same_key_in_two_items_cannot_cross_between_them():
    """A marker belongs to one item. One that arrives in another is refused."""

    first = f"Rule one cites {KEY} here."
    second = f"Rule two also cites {KEY} here."
    protector = _OpaqueText(
        {"rule-0": _spans(first, KEY), "rule-1": _spans(second, KEY)},
        texts=[first, second],
    )

    hidden_first = protector.hide("rule-0", first)
    hidden_second = protector.hide("rule-1", second)

    marker_of_first = next(
        token for token in hidden_first.split() if protector._prefix in token
    )
    marker_of_second = next(
        token for token in hidden_second.split() if protector._prefix in token
    )
    assert marker_of_first != marker_of_second, "two items were given one marker"

    # The second item coming back carrying the first item's marker.
    swapped = hidden_second.replace(marker_of_second, marker_of_first)
    with pytest.raises(EnglishProjectionError):
        protector.show("rule-1", swapped)


def test_two_keys_next_to_each_other_are_each_restored():
    """Adjacent positions are a case a backwards substitution has to get right."""

    other = "grade-band-3"
    text = f"See {KEY} {other} for the table."
    recorded = sorted(_spans(text, KEY) + _spans(text, other))

    protector = _OpaqueText({"rule-0": recorded}, texts=[text])
    assert protector.show("rule-0", protector.hide("rule-0", text)) == text


