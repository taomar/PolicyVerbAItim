def test_a_rendering_that_drops_a_key_is_refused():
    text = f"The entitlement under {KEY} is fixed."
    protector = _OpaqueText({"rule-0": _spans(text, KEY)}, texts=[text])
    hidden = protector.hide("rule-0", text)
    marker = next(token for token in hidden.split() if protector._prefix in token)

    with pytest.raises(EnglishProjectionError):
        protector.show("rule-0", hidden.replace(marker, ""))


def test_a_rendering_that_duplicates_a_key_is_refused():
    text = f"The entitlement under {KEY} is fixed."
    protector = _OpaqueText({"rule-0": _spans(text, KEY)}, texts=[text])
    hidden = protector.hide("rule-0", text)
    marker = next(token for token in hidden.split() if protector._prefix in token)

    with pytest.raises(EnglishProjectionError):
        protector.show("rule-0", f"{hidden} and again {marker}")


def test_a_rendering_that_alters_a_marker_is_refused():
    """A marker with a digit changed is not the marker that was sent."""

    text = f"The entitlement under {KEY} is fixed."
    protector = _OpaqueText({"rule-0": _spans(text, KEY)}, texts=[text])
    hidden = protector.hide("rule-0", text)
    marker = next(token for token in hidden.split() if protector._prefix in token)
    altered = marker[:-3] + "9" + marker[-2:]

    with pytest.raises(EnglishProjectionError):
        protector.show("rule-0", hidden.replace(marker, altered))


def test_positions_that_do_not_fit_their_text_are_refused():
    """Provenance that does not fit the string is not that string's provenance."""

    text = f"Under {KEY} the balance accrues."

    past_the_end = _OpaqueText({"rule-0": [(0, len(text) + 5)]}, texts=[text])
    with pytest.raises(EnglishProjectionError):
        past_the_end.hide("rule-0", text)

    overlapping = _OpaqueText({"rule-0": [(0, 10), (5, 15)]}, texts=[text])
    with pytest.raises(EnglishProjectionError):
        overlapping.hide("rule-0", text)

    inside_out = _OpaqueText({"rule-0": [(10, 4)]}, texts=[text])
    with pytest.raises(EnglishProjectionError):
        inside_out.hide("rule-0", text)


