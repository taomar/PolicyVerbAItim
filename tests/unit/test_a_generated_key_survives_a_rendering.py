"""A generated key comes back from a rendering exactly as it went in.

WHAT THIS FILE HOLDS

Some of what the index sends to be rendered into English is not language. A
fact's `name` is generated by this system to be matched later, character for
character. A renderer given one will do reasonable things to it -- split it at
its hyphens, tidy its digits, put its words in a better order -- and every one
of those makes it stop matching.

So each occurrence is held back from the rendering and put in afterwards. The
claims this file pins are about *which* occurrence, and they are the claims that
a simpler implementation gets wrong:

  * **A key is a position, not a spelling.** Generated keys spell ordinary
    words. Protecting every place a passage happens to spell one means refusing
    to render prose the document was merely speaking.
  * **One occurrence, one marker.** The same key legitimately appears more than
    once in a single text, so a marker standing for "that key, wherever it is"
    cannot be checked for having come back the right number of times.
  * **Items do not share provenance.** The policy and its rules are separate
    documents rendered in one call. A key generated for one says nothing about
    where those letters fall in another.
  * **Anything that did not come back is refused.** A dropped, duplicated,
    altered or foreign marker means the text that would result is not the text
    that was sent, and that is a build failure rather than a repair.
"""

from __future__ import annotations

import asyncio
import json
from types import SimpleNamespace

import pytest

from policy_platform.infrastructure.search import english_projection
from policy_platform.infrastructure.search.english_projection import (
    EnglishProjectionError,
    _OpaqueText,
    project_texts_to_english,
)
from tests.fixtures.search_stubs import contained_payload

#: A generated fact name. It spells two ordinary words, which is the whole
#: difficulty: a passage may say "annual leave" without meaning this key.
KEY = "annual-leave-7"

#: The same shape without a digit.
#:
#: Two protections now run over one text: keys are withheld by the positions
#: composition recorded, and numbers are withheld wherever they occur, because a
#: rendering that drops a quantity has changed what the passage can be found by.
#: A key that ends in a digit therefore reaches the renderer with that digit
#: already withheld — correct, and it makes a test about *key* positions unable
#: to tell which mechanism acted. The tests below that are specifically about
#: position-versus-spelling use this one, so what they measure is only the thing
#: they are named for. The interaction itself is pinned separately, by
#: `test_an_unrecorded_keys_digits_are_still_protected_as_numbers`.
LETTER_KEY = "annual-leave-carry"


def _run(coro):
    return asyncio.run(coro)


def _settings():
    return SimpleNamespace(
        search_enabled=True,
        ai_enabled=True,
        azure_openai_embedding_dimensions=3,
        azure_openai_secondary_deployment="fast",
        azure_openai_deployment="slow",
    )


class _Echo:
    """A renderer that returns what it was given, remembering what that was.

    Identity is the right stub here. These tests are not about how well a
    passage is rendered; they are about whether the characters that must not be
    rendered were withheld from it and restored afterwards. What the renderer
    was *sent* is the evidence, so it is recorded.
    """

    def __init__(self) -> None:
        self.payloads: list[dict] = []

    async def chat(self, messages, **_kwargs) -> str:
        payload = contained_payload(messages[-1]["content"])
        self.payloads.append(payload)
        return json.dumps(payload, ensure_ascii=False)

    def sent(self) -> str:
        """Everything the renderer saw, as one string."""

        return "\n".join(
            value for payload in self.payloads for value in payload.values()
        )


def _spans(text: str, term: str) -> list[tuple[int, int]]:
    """Every position of `term` in `text`.

    A test helper, deliberately not the product's method: the product carries
    positions down from where it composed the string. Finding them by value is
    fine for building a fixture and is exactly what must not happen in the
    product, which is why these tests then check the *prose* was left alone.
    """

    found, start = [], text.find(term)
    while start != -1:
        found.append((start, start + len(term)))
        start = text.find(term, start + 1)
    return found


