def test_prose_that_happens_to_spell_a_key_is_still_rendered():
    """The words a key is made of are not the key, and are not withheld.

    Measured on the live corpus rather than imagined: forty-one records there
    contain an opaque value inside unrelated prose, among them `employee`,
    `condition`, `action`, `object`, `leave` and `you`. A generated name is
    allowed to be an ordinary word, so protecting by spelling would refuse to
    render the places the document was merely speaking.

    The fixture uses such a name deliberately. Withholding by value replaces
    both occurrences here; withholding by position replaces only the one
    composition recorded.
    """

    plain_word_key = "leave"
    text = "Staff may leave early. The leave entitlement resets each year."
    recorded = _spans(text, plain_word_key)[1:]
    assert len(recorded) == 1, "fixture should record only the second occurrence"

    protector = _OpaqueText({"rule-0": recorded}, texts=[text])
    hidden = protector.hide("rule-0", text)

    assert "Staff may leave early." in hidden, (
        "prose was withheld as if it were a key; the document said this word, "
        "it did not name it"
    )
    assert "leave entitlement" not in hidden, "the recorded occurrence was not withheld"
    assert protector.show("rule-0", hidden) == text


def test_an_unrecorded_occurrence_is_left_for_the_renderer():
    """Only what composition recorded is protected -- nothing is found by value."""

    text = f"{LETTER_KEY} applies. Elsewhere the document also writes {LETTER_KEY} as prose."
    first_only = _spans(text, LETTER_KEY)[:1]

    protector = _OpaqueText({"rule-0": first_only}, texts=[text])
    hidden = protector.hide("rule-0", text)

    assert hidden.count(LETTER_KEY) == 1, "an occurrence nobody recorded was withheld anyway"
    assert protector.show("rule-0", hidden) == text


def test_an_unrecorded_key_is_protected_as_an_identifier_not_as_a_key():
    """The two protections overlap on a key that mixes letters and digits.

    Composition recorded one occurrence. The other is prose as far as *key*
    protection is concerned, and nothing finds it by value. It is protected all
    the same — not as a key, but because `annual-leave-7` is identifier-shaped,
    and identifier-shaped tokens are exactly what the validator will later
    require the rendering to have carried.

    That is the general rule rather than a special case for keys: every literal
    the validator requires is withheld, whoever generated it. Pinning it stops
    someone "simplifying" the identifier predicate into one that only covers
    tokens somebody recorded, which would put the unrecorded occurrence back at
    the mercy of the renderer.
    """

    text = f"{KEY} applies. Elsewhere the document also writes {KEY} as prose."
    first_only = _spans(text, KEY)[:1]

    protector = _OpaqueText({"rule-0": first_only}, texts=[text])
    hidden = protector.hide("rule-0", text)

    assert KEY not in hidden, "an identifier-shaped token was left for the renderer"
    assert not english_projection._identifiers(hidden), (
        "the hidden text still states an identifier the rendering must reproduce"
    )
    assert len(protector._expected["rule-0"]) == 2, (
        "the recorded occurrence and the identifier-shaped one should each be withheld once"
    )
    assert protector.show("rule-0", hidden) == text


def test_prose_around_an_unrecorded_key_still_reaches_the_renderer():
    """Protection is still of literals, not of the words beside them."""

    text = f"{KEY} applies. Elsewhere the document also writes {KEY} as prose."
    protector = _OpaqueText({"rule-0": _spans(text, KEY)[:1]}, texts=[text])
    hidden = protector.hide("rule-0", text)

    assert "Elsewhere the document also writes" in hidden
    assert "as prose." in hidden


