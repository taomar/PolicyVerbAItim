def test_a_key_comes_back_exactly_from_a_whole_rendering():
    """End to end, because a helper on its own does not run the caller's code."""

    text = f"Under {KEY} the balance accrues for staff."
    client = _Echo()

    rendered = _run(
        project_texts_to_english(
            [("rule-0", text)],
            settings=_settings(),
            openai_client=client,
            opaque_spans={"rule-0": _spans(text, KEY)},
        )
    )

    assert rendered["rule-0"] == text
    assert KEY not in client.sent(), "the key was sent to the renderer after all"


def test_a_rules_positions_do_not_reach_into_the_policy_text():
    """One item's provenance cannot protect another item's prose.

    The policy here spells the rule's key as ordinary words. Nothing recorded
    it there, so it must go to the renderer as language -- and the rule's own
    occurrence must not. Both halves are checked against what was actually
    sent, because that is where a shared term set would show.
    """

    policy = f"The handbook explains {LETTER_KEY} in plain terms for readers."
    rule = f"Under {LETTER_KEY} the balance accrues."
    client = _Echo()

    rendered = _run(
        project_texts_to_english(
            [("policy", policy), ("rule-0", rule)],
            settings=_settings(),
            openai_client=client,
            opaque_spans={"rule-0": _spans(rule, LETTER_KEY)},
        )
    )

    assert rendered["policy"] == policy
    assert rendered["rule-0"] == rule

    sent = [value for payload in client.payloads for value in payload.values()]
    carrying = [value for value in sent if LETTER_KEY in value]
    assert len(carrying) == 1, (
        "exactly one item should have reached the renderer still spelling the key"
    )
    assert carrying[0].startswith("The handbook explains"), (
        "the policy's plain-language occurrence should have been rendered and the "
        "rule's recorded one withheld; a shared term set gets this backwards"
    )


def test_a_text_with_no_recorded_positions_is_rendered_untouched():
    """Nothing is protected by default, so a clean text is not marked up at all."""

    text = "Staff may take annual leave each year."
    client = _Echo()

    rendered = _run(
        project_texts_to_english(
            [("rule-0", text)], settings=_settings(), openai_client=client
        )
    )

    assert rendered["rule-0"] == text
    assert client.sent() == text
