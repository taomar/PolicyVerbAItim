def test_a_marker_stem_the_source_already_spells_is_lengthened():
    """A marker only works because nothing else looks like it, so that is checked."""

    text = f"This text mentions {_OpaqueText._STEM} on purpose."
    protector = _OpaqueText({"rule-0": []}, texts=[text])

    assert protector._prefix != _OpaqueText._STEM
    assert protector._prefix not in text


def test_the_marker_is_inert_to_every_check_the_validator_makes():
    """A marker must not itself be a literal the validator then requires.

    THIS INVERTS AN EARLIER DECISION, AND THE MEASUREMENT IS WHY

    The marker used to carry its ordinal in digits, deliberately, so that the
    preservation check already here would catch a mangled one. That reasoning
    was sound while only recorded keys were protected -- there were few of them,
    and they were identifier-shaped in the source anyway.

    It stopped being sound once every number was protected too. The validator
    asks which numbers a text states and which identifier-shaped tokens it
    states; a digit-bearing marker answers the second. So protecting a plain
    number *created* an identifier the source never contained, and the renderer
    was then required to reproduce it exactly. Measured over one real corpus:
    2,277 identifier tokens existed only because a number had been protected,
    against 83 the documents themselves stated. A live rebuild was refused for
    losing five of them.

    The guarantee did not weaken; it moved to a stricter check.
    `protected_literal_failure` refuses a dropped or duplicated marker per item
    and per attempt, so it is still caught during rendering and still retried --
    and `show` refuses anything that survives that. Both are exact-occurrence
    rules, where the identifier check was set membership.
    """

    text = f"Under {KEY} the balance accrues within 30 days."
    protector = _OpaqueText({"rule-0": _spans(text, KEY)}, texts=[text])
    hidden = protector.hide("rule-0", text)

    assert not english_projection._identifiers(hidden), (
        "a marker is an identifier again, so protecting a literal now requires one"
    )
    assert not english_projection._numbers(hidden), (
        "a marker states a number, so protecting a literal now requires one"
    )
    assert english_projection.preservation_failure(hidden, hidden) is None

    # The guarantee, at its new home: losing one is still refused, during
    # rendering, by a check that names counts and no values.
    dropped = hidden.replace(protector._expected["rule-0"][0], "", 1)
    reason = english_projection.protected_literal_failure(hidden, dropped)
    assert reason is not None
    assert "protected literal" in reason
    assert KEY not in reason and "30" not in reason


